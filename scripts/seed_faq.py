async def seed_faq() -> None:
    await init_models()
    async with AsyncSessionLocal() as session:
        # Очищаем таблицу FAQ перед загрузкой актуальных 10 вопросов
        await session.execute(delete(Faq))
        for item in FAQS_DATA:
            new_faq = Faq(
                question=item["question"],
                answer=item["answer"],
                sort_order=item["sort_order"],
            )
            session.add(new_faq)
            print(f"  [{item['sort_order']}] {item['question']}")
        await session.commit()
    print("✓ Загрузка 10 вопросов FAQ завершена.")


if __name__ == "__main__":
    asyncio.run(seed_faq())
